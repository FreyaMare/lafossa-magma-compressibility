"""Copy the code cells of the any-volcano notebook into the program (magma_uplift/nbcells.py).

Run after changing notebooks/Magma_Compressibility_Uplift_AnyVolcano.ipynb:
    pip install nbformat markdown
    python windows_app/tools/make_cells.py
The program runs these cells verbatim, so its results stay identical to the notebook's.
"""
import pathlib
import re

import markdown
import nbformat

ROOT = pathlib.Path(__file__).resolve().parents[2]
NB = ROOT / "notebooks" / "Magma_Compressibility_Uplift_AnyVolcano.ipynb"
OUT = ROOT / "windows_app" / "magma_uplift" / "nbcells.py"

nb = nbformat.read(NB, 4)
cells, titles, md = {}, {}, []
for c in nb.cells:
    if c.cell_type == "markdown":
        md.append(c.source)
        continue
    m = re.match(r"#@title (\d+)\. (.*?)\s*\{", c.source)
    n = int(m.group(1))
    cells[n] = c.source
    titles[n] = m.group(2).strip()
assert sorted(cells) == list(range(1, 19)), sorted(cells)
intro, guide, refs = md
html = lambda s: markdown.markdown(s, extensions=["tables"])
with OUT.open("w", encoding="utf-8") as f:
    f.write('"""Code cells of the notebook "From magma compressibility to surface uplift", copied verbatim\n'
            '(generated by tools/make_cells.py; do not edit by hand)."""\n')
    f.write(f"TITLES = {titles!r}\n")
    f.write(f"INTRO_HTML = {html(intro)!r}\n")
    f.write(f"GUIDE_HTML = {html(guide)!r}\n")
    f.write(f"REFS_HTML = {html(refs)!r}\n")
    f.write("CELLS = {}\n")
    for n, src in cells.items():
        f.write(f"CELLS[{n}] = {src!r}\n")
print(OUT, OUT.stat().st_size, "bytes")
